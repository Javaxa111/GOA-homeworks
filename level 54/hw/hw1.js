function add(a, b) {
    return a + b;
}

function subtract(a, b) {
    return a - b;
}

function division(a, b) {
    return a / b;
}

function multiplication(a, b) {
    return a * b;
}


console.log(add(10, 5));        
console.log(subtract(10, 5));    
console.log(division(10, 5));    
console.log(multiplication(10, 5));